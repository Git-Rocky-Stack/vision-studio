import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { cleanup, render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';

import { useAppStore } from '@/store/appStore';
import type { AssetRecord } from '@/types/assets';
import { CollectionsPage } from '@/pages/CollectionsPage';
import { columnsFor } from './CollectionDetail';
import { customTagId, nextSmartCollectionName, SmartCollectionDialog } from './SmartCollectionDialog';

vi.mock('@tanstack/react-virtual', () => ({
  useVirtualizer: ({ count }: { count: number }) => ({
    getTotalSize: () => count * 100,
    getVirtualItems: () => Array.from({ length: count }, (_, index) => ({ index, key: index, start: index * 100 })),
    measure: () => {},
  }),
}));

function asset(i: number, prompt: string, model: string, createdAt: string): AssetRecord {
  return {
    id: `asset-${i}`,
    jobId: `job-${i}`,
    name: `render-${i}.png`,
    type: 'image',
    path: `C:/out/render-${i}.png`,
    previewUrl: `file:///C:/out/render-${i}.png`,
    thumbnail: `file:///C:/out/thumb-${i}.png`,
    createdAt,
    prompt,
    negativePrompt: '',
    model,
    favorite: false,
    params: {},
  };
}

function seedLibrary() {
  useAppStore.setState({
    assetLibrary: [
      asset(0, 'a cinematic hero shot of a bridge', 'sdxl', '2026-03-10T12:00:00'),
      asset(1, 'a serene landscape', 'flux-dev', '2026-05-02T12:00:00'),
      asset(2, 'hero shot portrait', 'flux-dev', '2026-06-20T12:00:00'),
    ],
  });
}

describe('SmartCollectionDialog', () => {
  beforeEach(() => {
    useAppStore.setState(useAppStore.getInitialState(), true);
    seedLibrary();
  });
  afterEach(cleanup);

  it('is a labelled modal that focuses the name field and needs a rule before it can create', async () => {
    render(<SmartCollectionDialog open onClose={vi.fn()} />);
    const dialog = screen.getByRole('dialog', { name: 'New smart collection' });
    expect(dialog).toHaveAttribute('aria-modal', 'true');
    await vi.waitFor(() => expect(screen.getByRole('textbox', { name: 'Name' })).toHaveFocus());
    expect(screen.getByRole('textbox', { name: 'Name' })).toHaveValue('Smart Collection');
    expect(screen.getByText('Add at least one rule to build the collection.')).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Create smart collection' })).toBeDisabled();
  });

  it('previews the live match count and creates, fills and opens the collection', async () => {
    const user = userEvent.setup();
    const onClose = vi.fn();
    render(<SmartCollectionDialog open onClose={onClose} />);

    await user.selectOptions(screen.getByRole('combobox', { name: 'Model' }), 'flux-dev');
    expect(screen.getByText('2 of 3 assets match')).toBeInTheDocument();

    await user.type(screen.getByRole('textbox', { name: 'Prompt contains' }), 'portrait');
    expect(screen.getByText('1 of 3 assets match')).toBeInTheDocument();

    const name = screen.getByRole('textbox', { name: 'Name' });
    await user.clear(name);
    await user.type(name, 'Flux portraits');
    await user.click(screen.getByRole('button', { name: 'Create smart collection' }));

    const created = useAppStore.getState().collections[0];
    expect(created).toMatchObject({
      name: 'Flux portraits',
      type: 'smart',
      isAutoGenerated: false,
      smartQuery: { model: 'flux-dev', promptText: 'portrait' },
      assetIds: ['asset-2'],
    });
    expect(useAppStore.getState().activeCollectionId).toBe(created.id);
    expect(onClose).toHaveBeenCalled();
  });

  it('authors a custom tag, matches it against prompts, and can delete it', async () => {
    const user = userEvent.setup();
    render(<SmartCollectionDialog open onClose={vi.fn()} />);

    await user.click(screen.getByRole('button', { name: 'Add tag' }));
    expect(screen.getByRole('alert')).toHaveTextContent('Type a tag name first.');

    await user.type(screen.getByRole('textbox', { name: 'Add a custom tag' }), 'Hero Shot{Enter}');
    expect(useAppStore.getState().availableTags).toContainEqual(
      expect.objectContaining({ id: customTagId('Hero Shot'), name: 'hero shot', category: 'custom', source: 'user' }),
    );
    expect(screen.getByRole('button', { name: 'hero shot', pressed: true })).toBeInTheDocument();
    expect(screen.getByText('2 of 3 assets match')).toBeInTheDocument();

    await user.click(screen.getByRole('button', { name: 'Delete custom tag hero shot' }));
    expect(useAppStore.getState().availableTags).toHaveLength(0);
    expect(screen.getByText('Add at least one rule to build the collection.')).toBeInTheDocument();
  });

  it('refuses a date window whose start is after its end', async () => {
    const user = userEvent.setup();
    render(<SmartCollectionDialog open onClose={vi.fn()} />);
    await user.type(screen.getByLabelText('From'), '2026-06-01');
    await user.type(screen.getByLabelText('To'), '2026-04-01');
    expect(screen.getByRole('alert')).toHaveTextContent('The start date is after the end date.');
    expect(screen.getByRole('button', { name: 'Create smart collection' })).toBeDisabled();
  });

  it('requires a name', async () => {
    const user = userEvent.setup();
    render(<SmartCollectionDialog open onClose={vi.fn()} />);
    await user.selectOptions(screen.getByRole('combobox', { name: 'Model' }), 'sdxl');
    await user.clear(screen.getByRole('textbox', { name: 'Name' }));
    await user.click(screen.getByRole('button', { name: 'Create smart collection' }));
    expect(screen.getByText('Name the collection.')).toBeInTheDocument();
    expect(useAppStore.getState().collections).toHaveLength(0);
  });

  it('closes on Escape', async () => {
    const user = userEvent.setup();
    const onClose = vi.fn();
    render(<SmartCollectionDialog open onClose={onClose} />);
    await user.keyboard('{Escape}');
    expect(onClose).toHaveBeenCalledTimes(1);
  });
});

describe('Smart collections on the Collections page', () => {
  beforeEach(() => {
    useAppStore.setState(useAppStore.getInitialState(), true);
    seedLibrary();
  });
  afterEach(cleanup);

  it('opens the editor from the header and lists the result under the Smart filter', async () => {
    const user = userEvent.setup();
    render(<CollectionsPage />);
    await user.click(screen.getByRole('button', { name: 'Smart Collection' }));
    await user.selectOptions(screen.getByRole('combobox', { name: 'Model' }), 'sdxl');
    await user.click(screen.getByRole('button', { name: 'Create smart collection' }));

    await user.click(screen.getByRole('button', { name: 'Smart' }));
    expect(screen.getByRole('button', { name: /smart collection collection, 1 asset/i })).toBeInTheDocument();
    expect(screen.getByText('model: sdxl')).toBeInTheDocument();
  });

  it('re-runs a smart collection against the library from its card', async () => {
    const user = userEvent.setup();
    useAppStore.getState().createSmartCollection({ name: 'Flux', smartQuery: { model: 'flux-dev' } });
    render(<CollectionsPage />);
    expect(screen.getByRole('button', { name: /flux collection, 0 assets/i })).toBeInTheDocument();

    await user.click(screen.getByRole('button', { name: 'Refresh Flux' }));
    expect(useAppStore.getState().collections[0].assetIds).toEqual(['asset-1', 'asset-2']);
    const detail = screen.queryByRole('region', { name: 'Flux assets' });
    expect(detail).toBeNull();
    const card = screen.getByRole('button', { name: /flux collection, 2 assets/i });
    await user.click(card);
    expect(within(screen.getByRole('region', { name: 'Flux assets' })).getAllByRole('img')).toHaveLength(2);
  });
});

describe('collection helpers', () => {
  it('names smart collections distinctly', () => {
    expect(nextSmartCollectionName([])).toBe('Smart Collection');
    expect(nextSmartCollectionName(['Smart Collection'])).toBe('Smart Collection 2');
  });

  it('fits auto-fill columns of 120px tiles with 12px gaps', () => {
    expect(columnsFor(0)).toBe(1);
    expect(columnsFor(119)).toBe(1);
    expect(columnsFor(252)).toBe(2);
    expect(columnsFor(800)).toBe(6);
  });
});
